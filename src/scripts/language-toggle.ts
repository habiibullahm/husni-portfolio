const textNodes: Array<{ node: Text; original: string }> = [];
const textWalker = document.createTreeWalker(document.body, NodeFilter.SHOW_TEXT);
let currentNode = textWalker.nextNode();
while (currentNode) {
  const parentTag = currentNode.parentElement?.tagName;
  if (parentTag !== 'SCRIPT' && parentTag !== 'STYLE') {
    textNodes.push({ node: currentNode as Text, original: currentNode.textContent ?? '' });
  }
  currentNode = textWalker.nextNode();
}

const labelElements = [...document.querySelectorAll<HTMLElement>('[aria-label]')];
const originalLabels = labelElements.map((element) => ({ element, original: element.getAttribute('aria-label') ?? '' }));

const setLanguage = (language: 'en' | 'id') => {
  for (const { node, original } of textNodes) {
    const trimmed = original.trim();
    const translated = language === 'id' ? translations[trimmed] : undefined;
    node.textContent = original.replace(trimmed, translated ?? trimmed);
  }

  for (const { element, original } of originalLabels) {
    if (element.hasAttribute('data-language-toggle')) continue;
    element.setAttribute('aria-label', language === 'id' ? translations[original] ?? original : original);
  }

  document.documentElement.lang = language;
  for (const button of document.querySelectorAll<HTMLButtonElement>('[data-language-toggle]')) {
    button.textContent = language === 'en' ? 'ID' : 'EN';
    button.setAttribute('aria-label', language === 'en' ? 'Ganti bahasa ke Bahasa Indonesia' : 'Switch language to English');
    button.setAttribute('aria-pressed', String(language === 'id'));
  }

  try {
    localStorage.setItem('portfolio-language', language);
  } catch {
    // Language switching remains available when storage is disabled.
  }
};

document.querySelectorAll<HTMLButtonElement>('[data-language-toggle]').forEach((button) => {
  button.addEventListener('click', () => setLanguage(document.documentElement.lang === 'en' ? 'id' : 'en'));
});

let initialLanguage: string | null = null;
try {
  initialLanguage = localStorage.getItem('portfolio-language');
} catch {
  initialLanguage = null;
}
setLanguage(initialLanguage === 'id' ? 'id' : 'en');
